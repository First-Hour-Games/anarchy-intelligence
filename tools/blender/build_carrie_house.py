def build_cladding(layout, walls: list | None = None) -> None:
    """Stone foundation, water table with a drip cap, siding, frieze and corner boards over each
    outside wall, with the openings left clear. Under the porch the water table comes down to the
    deck."""
    h = HEIGHTS
    for w in walls or layout.walls:
        if not w["id"].startswith("Ext"):
            continue
        kit = Kit(w["id"] + "_Cladding")
        wraps = w["axis"] == "x"                 # the front and back skins wrap the corners

        def band(heights, depth, mat, holes=True):
            pieces = wall_spans(w, *heights) if holes else [(w["start"], w["end"], *heights)]
            for a, b, bottom, top in pieces:
                if wraps:
                    a -= depth if a <= w["start"] + 1e-6 else 0.0
                    b += depth if b >= w["end"] - 1e-6 else 0.0
                kit.along(w["axis"], (a, b), (bottom, top), depth_range(w, 0.0, depth), mat)

        porch = w["id"] == "ExtFront"
        band((h["stone"][0], h["deck"] if porch else h["stone"][1]), 0.03, "Stone")
        band((h["deck"] if porch else h["water_table"][0], h["water_table"][1]), 0.035, "Trim")
        band(h["drip"], 0.055, "Trim")
        band(h["siding"], 0.02, "Siding")
        band(h["frieze"], 0.025, "Trim", holes=False)
        corners = ((w["start"], w["start"] + 0.12), (w["end"] - 0.12, w["end"]))
        if wraps:
            corners = ((w["start"] - 0.03, w["start"] + 0.12), (w["end"] - 0.12, w["end"] + 0.03))
        for s in corners:
            kit.along(w["axis"], s, (h["siding"][0], h["frieze"][0]), depth_range(w, 0.0, 0.03), "Trim")
        kit.build()


