"""Build Carrie's house in models/source/buildings/CarrieHouse.blend.

Headless: blender --background --python tools/blender/build_carrie_house.py
Live (Blender MCP): runpy.run_path(<this file>, run_name="live")["build"]()

The layout lives in tools/blender/carrie_house/layout.py. Everything is rebuilt from scratch
in the "CarrieHouse" collection under the "HouseRoot" empty. HouseRoot rotates +90 degrees about
X, so children are authored in game coordinates: y up, +z out of the front door. Room labels,
a yard patch and a player-sized block for scale go in "CarrieHouseAids", which is never exported.

Stages: "structure" is the shell (walls, floors, stairs, roof, porch, chimney); "exterior"
finishes the outside (siding, stone foundation, shingles, brick, porch boards, trim, windows,
doors, gutters and porch details); "interior" finishes the rooms (wallpaper, floors and ceilings
by room, baseboards and wainscots, interior doors, the stair balustrade, radiators and light
fittings); "objects" adds the role-coloured furniture blocks; "aids" the editing aids. Without
"exterior" and "interior" the shell keeps its flat grey-box colours. Textures come from
assets/local_licensed/carrie_house_textures (CC0 downloads, and wallpapers generated by
tools/blender/carrie_house/wallpapers.py).
"""

