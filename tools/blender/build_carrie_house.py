def build_finished_porch(layout, back: bool = True) -> None:
    """Brick piers under tapered columns, box beams, a haint-blue ceiling, balustrades, square
    lattice skirting, brick cheeks beside the steps, and (with back) the back stoop's roof on
    brackets."""
    deck = HEIGHTS["deck"]
    line = PORCH_LINE
    xs, zs, ys, thickness = PORCH_ROOF
    deck_rect = next(f[3] for f in layout.floors if f[0] == "PorchDeck")
    steps = next(s for s in layout.stairs if s["id"] == "PorchSteps")
    step_x0, step_x1 = steps["x"]
    gaps = [(a, b) for a, b in zip(PORCH_PIERS, PORCH_PIERS[1:]) if not (a < step_x0 and step_x1 < b)]

    def under(z):                                   # underside of the porch roof at z
        return ys[0] + (z - zs[0]) / (zs[1] - zs[0]) * (ys[1] - ys[0]) - thickness

    frame = Kit("PorchFrame")
    for x in PORCH_PIERS:
        frame.box((x - 0.2, layout.GRADE, line - 0.2), (x + 0.2, 1.3, line + 0.2), "Brick")
        frame.box((x - 0.23, 1.3, line - 0.23), (x + 0.23, 1.37, line + 0.23), "Concrete")
        frame.add(frustum(x, line, 1.37, 3.04, 0.13, 0.09), BOX_FACES, "Trim")
        frame.box((x - 0.12, 3.04, line - 0.12), (x + 0.12, 3.1, line + 0.12), "Trim")
    frame.box((xs[0] + 0.18, 3.1, line - 0.11), (xs[1] - 0.18, 3.42, line + 0.11), "Trim")
    for x in (PORCH_PIERS[0], PORCH_PIERS[-1]):
        frame.slanted("z", (x - 0.1, x + 0.1), zs[0], line - 0.11, 3.1,
                      under(zs[0]) + 0.04, under(line - 0.11) + 0.04, "Trim")
    frame.box((PORCH_PIERS[0] + 0.1, 3.3, zs[0]), (PORCH_PIERS[-1] - 0.1, 3.32, line - 0.11), "PorchCeiling")
    door = next(o for w in layout.walls if w["id"] == "ExtFront" for o in w["openings"] if o["kind"] == "door")
    lamp_x = (door["a"] + door["b"]) / 2.0                                   # porch light over the door
    frame.box((lamp_x - 0.08, 3.27, 0.92), (lamp_x + 0.08, 3.3, 1.08), "Brass")
    frame.box((lamp_x - 0.1, 3.14, 0.9), (lamp_x + 0.1, 3.27, 1.1), "MilkGlass")
    for a, b in ((step_x0 - 0.18, step_x0), (step_x1, step_x1 + 0.18)):     # brick cheeks by the steps
        frame.box((a, layout.GRADE, line + 0.2), (b, deck + 0.07, steps["z"][1] + 0.02), "Brick")
        frame.box((a - 0.01, deck + 0.07, line + 0.2), (b + 0.01, deck + 0.11, steps["z"][1] + 0.03), "Concrete")
    frame.build()
    sloped_slab("PorchRoof", xs, zs, ys, thickness, SLAB_FINISH)

    rails = Kit("PorchRails")

    def balustrade(axis, s0, s1, c):
        rails.along(axis, (s0, s1), (deck + 0.7, deck + 0.76), (c - 0.045, c + 0.045), "Trim")
        rails.along(axis, (s0, s1), (deck + 0.07, deck + 0.12), (c - 0.035, c + 0.035), "Trim")
        count = max(1, round((s1 - s0) / 0.12))
        for i in range(count):
            s = s0 + (s1 - s0) * (i + 0.5) / count
            rails.along(axis, (s - 0.02, s + 0.02), (deck + 0.12, deck + 0.7), (c - 0.02, c + 0.02), "Trim")

    for a, b in gaps:
        balustrade("x", a + 0.2, b - 0.2, line)
    for x in (PORCH_PIERS[0], PORCH_PIERS[-1]):
        rails.box((x - 0.06, deck, zs[0]), (x + 0.06, deck + 0.85, zs[0] + 0.12), "Trim")     # newel by the house
        balustrade("z", zs[0] + 0.12, line - 0.2, x)
    rails.build()

    skirt = Kit("PorchSkirt")

    def lattice(axis, s0, s1, face, out):
        def c(d0, d1):
            return (face + out * d0, face + out * d1)
        skirt.along(axis, (s0, s1), (deck - 0.15, deck), c(0.0, 0.02), "Trim")              # rim board
        skirt.along(axis, (s0, s1), (layout.GRADE, layout.GRADE + 0.05), c(0.0, 0.02), "Trim")
        count = max(1, round((s1 - s0) / 0.1))
        for i in range(count + 1):
            s = s0 + (s1 - s0) * i / count
            skirt.along(axis, (s - 0.015, s + 0.015), (layout.GRADE + 0.05, deck - 0.15), c(0.0, 0.012), "Trim")
        for y in (0.13, 0.23, 0.33):
            skirt.along(axis, (s0, s1), (layout.GRADE + y, layout.GRADE + y + 0.03), c(0.006, 0.018), "Trim")

    for a, b in gaps:
        lattice("x", a + 0.2, b - 0.2, deck_rect[3], 1.0)
    lattice("z", deck_rect[2], line - 0.2, deck_rect[0], -1.0)
    lattice("z", deck_rect[2], line - 0.2, deck_rect[1], 1.0)
    for sign in (-1.0, 1.0):                         # deck ends showing past the house corners
        skirt.box((sign * (HOUSE[1] + 0.03), layout.GRADE, deck_rect[2] - 0.02), (sign * (deck_rect[1] + 0.02), deck, deck_rect[2]), "Trim")
    skirt.box((step_x0, layout.GRADE, deck_rect[3]), (step_x1, deck, deck_rect[3] + 0.005), "Treads")   # top riser
    skirt.build()
    if not back:
        return

    Kit("BackStoopRoof").box((1.4, 3.05, -11.2), (3.1, 3.15, -10.1), "Trim", top="Shingles").build()
    brackets = Kit("BackStoopBrackets")
    for x in (1.5, 3.0):
        verts = [(x - 0.03, 2.6, HOUSE[2]), (x - 0.03, 3.05, HOUSE[2]), (x - 0.03, 3.05, -10.9),
                 (x + 0.03, 2.6, HOUSE[2]), (x + 0.03, 3.05, HOUSE[2]), (x + 0.03, 3.05, -10.9)]
        brackets.add(verts, [(0, 1, 2), (3, 5, 4), (0, 3, 4, 1), (1, 4, 5, 2), (2, 5, 3, 0)], "Trim")
    brackets.build()


