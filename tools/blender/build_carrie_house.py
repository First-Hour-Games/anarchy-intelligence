def build_hip_caps(layout) -> None:
    """Capping along the four hips, from a little above the eave corners to the apex."""
    from mathutils import Vector
    x0, x1, z0, z1 = ROOF_RIM
    eave = HEIGHTS["eave"]
    apex = Vector(((x0 + x1) / 2.0, eave + (x1 - x0) / 2.0 * ROOF_PITCH, (z0 + z1) / 2.0))
    corners = [Vector((x0, eave, z1)), Vector((x1, eave, z1)), Vector((x1, eave, z0)), Vector((x0, eave, z0))]
    kit = Kit("RoofHips")
    for i, corner in enumerate(corners):
        hip = (apex - corner).normalized()
        sides = []
        for other in (corners[i - 1], corners[(i + 1) % 4]):
            normal = (other - corner).cross(apex - corner).normalized()
            if normal.y < 0.0:
                normal = -normal
            across = normal.cross(hip).normalized()
            if across.dot(other - corner) < 0.0:
                across = -across
            sides.append((normal, across))
        ridge = (sides[0][0] + sides[1][0]).normalized()
        verts = []
        for point in (corner + hip * 0.15, apex):
            verts += [point + ridge * 0.04,
                      point + sides[0][1] * 0.1 + sides[0][0] * 0.01,
                      point + sides[1][1] * 0.1 + sides[1][0] * 0.01]
        kit.add(verts, [(0, 3, 4, 1), (0, 2, 5, 3), (1, 4, 5, 2), (0, 1, 2), (3, 5, 4)], "Shingles")
    kit.build()


