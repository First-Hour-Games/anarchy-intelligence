def build_roof(layout) -> None:
    """Pyramidal hip roof with a front dormer; the attic sits inside it."""
    x0, x1, z0, z1 = ROOF_RIM
    eave = layout.ATTIC - ROOF_OVERHANG * ROOF_PITCH
    apex_y = eave + (x1 - x0) / 2.0 * ROOF_PITCH
    cx, cz = (x0 + x1) / 2.0, (z0 + z1) / 2.0
    t = 0.15
    outer = [(x0, eave, z1), (x1, eave, z1), (x1, eave, z0), (x0, eave, z0), (cx, apex_y, cz)]
    inner = [(x0 + 0.25, eave, z1 - 0.25), (x1 - 0.25, eave, z1 - 0.25), (x1 - 0.25, eave, z0 + 0.25),
             (x0 + 0.25, eave, z0 + 0.25), (cx, apex_y - t / 0.86, cz)]
    faces = [(0, 1, 4), (1, 2, 4), (2, 3, 4), (3, 0, 4),                    # outside slopes
             (5, 9, 6), (6, 9, 7), (7, 9, 8), (8, 9, 5),                    # attic side
             (0, 5, 6, 1), (1, 6, 7, 2), (2, 7, 8, 3), (3, 8, 5, 0)]        # eave edges
    detailed = DETAILED[0]
    underside = "Sheathing" if INTERIOR[0] else "AtticWood"
    Kit("Roof").add(outer + inner, faces, (["Shingles"] * 4 + [underside] * 4 + ["Trim"] * 4) if detailed else "Roof").build()
    # Front dormer lighting the attic.
    box("Dormer", (-1.1, layout.ATTIC - 0.2, -2.6), (1.1, layout.ATTIC + 1.7, -0.25), "Siding" if detailed else "Exterior")
    if not detailed:
        box("DormerWindow", (-0.6, layout.ATTIC + 0.4, -0.27), (0.6, layout.ATTIC + 1.3, -0.23), "Glass")
    sloped_slab("DormerRoof", (-1.35, 1.35), (-0.05, -2.9), (layout.ATTIC + 1.95, layout.ATTIC + 1.75), 0.12,
                SLAB_FINISH if detailed else "Roof")


