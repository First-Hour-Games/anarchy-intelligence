def build_stair_rail(layout) -> None:
    """The main stair's open side: a closed stringer carrying balusters and a handrail between
    newels, then a kneewall where the upstairs wall comes down over it, and a short rail round the
    stairwell at the top."""
    stair = next(s for s in layout.stairs if s["id"] == "MainStair")
    (x_low, _), (p0, p1), (y0, y1), n = stair["x"], stair["z"], stair["y"], stair["risers"]
    run, rise = (p1 - p0) / n, (y1 - y0) / n
    x = x_low - 0.04                                       # over the stringer wall below
    side = (x - 0.04, x + 0.04)
    rail_height, kit = 0.86, Kit("MainStairRail")

    def pitch(z):                                          # nosing line
        return y0 + rise + (z - p0) / run * rise

    def rail(z):
        return pitch(z) + rail_height

    # Where the handrail would run into the upstairs floor, the side closes up to it.
    z_wall = p0 + (y1 - 0.05 - rail_height - (y0 + rise)) / rise * run
    # The bottom newel stands on the first tread, so the floor in front of the stair stays clear.
    newel = p0 + (0.065 if p1 > p0 else -0.065)
    kit.add(run_prism("z", side, p0, z_wall, (pitch(p0) - 0.3, pitch(p0) + 0.05), (pitch(z_wall) - 0.3, pitch(z_wall) + 0.05)), BOX_FACES, "Trim")
    kit.add(run_prism("z", side, z_wall, p1, (pitch(z_wall) - 0.3, y1), (pitch(p1) - 0.3, y1)), BOX_FACES, "Plaster")
    kit.add(run_prism("z", (x - 0.035, x + 0.035), newel, z_wall, (rail(newel) - 0.03, rail(newel) + 0.03),
                      (rail(z_wall) - 0.03, rail(z_wall) + 0.03)), BOX_FACES, "WoodTrim")
    for i in range(n):
        for z in (p0 + (i + 0.25) * run, p0 + (i + 0.75) * run):
            if (z - z_wall) * (p0 - z_wall) > 0.0:         # below the kneewall
                kit.box((x - 0.0175, pitch(z) + 0.05, z - 0.0175), (x + 0.0175, rail(z) - 0.03, z + 0.0175), "Trim")
    for z, bottom, top in ((newel, y0, y0 + 1.15), (z_wall, pitch(z_wall) - 0.3, y1), (p1, y1 - 0.35, y1 + 1.0)):
        kit.box((x - 0.065, bottom, z - 0.065), (x + 0.065, top, z + 0.065), "WoodTrim")              # newels
        if top > y1 or bottom >= y0 and top < y1:
            kit.box((x - 0.085, top, z - 0.085), (x + 0.085, top + 0.05, z + 0.085), "WoodTrim")
    # Round the stairwell at the top, to the end of the parents' room wall.
    end = next(w["start"] for w in layout.walls if w["id"] == "U_ParentsEast")
    top_rail = y1 + rail_height
    kit.box((x - 0.035, top_rail - 0.03, p1), (x + 0.035, top_rail + 0.03, end), "WoodTrim")
    kit.box((x - 0.03, y1, p1), (x + 0.03, y1 + 0.06, end), "WoodTrim")
    count = max(1, round(abs(end - p1) / 0.11))
    for k in range(1, count):
        z = p1 + (end - p1) * k / count
        kit.box((x - 0.0175, y1 + 0.06, z - 0.0175), (x + 0.0175, top_rail - 0.03, z + 0.0175), "Trim")
    kit.build()


