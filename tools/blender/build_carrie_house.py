# --- Editing aids ---------------------------------------------------------------------------------

def label(text: str, x: float, y: float, z: float, size: float = 0.32) -> None:
    curve = bpy.data.curves.new("Label", "FONT")
    curve.body = text
    curve.size = size
    curve.align_x = "CENTER"
    curve.align_y = "CENTER"
    curve.materials.append(material("Label"))
    obj = bpy.data.objects.new("Label_" + text.replace(" ", ""), curve)
    collection(AIDS).objects.link(obj)
    obj.parent = house_root()
    obj.location = (x, y, z)
    obj.rotation_euler = (radians(-90.0), 0.0, 0.0)       # lying on the floor, readable from the front


def build_aids(layout) -> None:
    box("Yard", (-9.0, -0.04, -15.0), (9.0, 0.0, 8.0), "Yard", AIDS)
    box("PlayerSize", (2.0, layout.GROUND - 0.05, 1.2), (2.7, layout.GROUND + 1.75, 1.9), "Scale", AIDS)
    for name, y, x0, x1, z0, z1 in layout.rooms:
        label(name, (x0 + x1) / 2.0, y + 0.02, (z0 + z1) / 2.0)


STAGES = ["structure", "exterior", "interior", "objects", "aids"]


def build(stages: list | None = None) -> None:
    layout = load_layout()
    clear()
    _materials.clear()
    house_root()
    stages = stages or STAGES
    DETAILED[0] = "exterior" in stages
    INTERIOR[0] = "interior" in stages
    HEIGHTS.clear()
    HEIGHTS.update(exterior_heights(layout))
    if "structure" in stages:
        for w in layout.walls:
            level = "Exterior walls" if w["id"].startswith("Ext") else "Upstairs" if w["y0"] >= layout.UPPER - 0.01 else "Ground floor"
            with part(level):
                build_wall(w, layout)
        floor_parts = {"CellarFloor": "Cellar", "GroundFloor": "Ground floor", "UpperFloor": "Upstairs",
                       "AtticFloor": "Upstairs", "PorchDeck": "Porch and yard", "BackStoop": "Porch and yard"}
        for name, y_top, thickness, rect, holes in layout.floors:
            with part(floor_parts[name]):
                build_floor(name, y_top, thickness, rect, holes, layout)
        stair_parts = {"MainStair": "Ground floor", "BackStair": "Ground floor", "CellarStair": "Cellar",
                       "AtticLadder": "Upstairs"}
        for s in layout.stairs:
            with part(stair_parts.get(s["id"], "Porch and yard")):
                build_stair(s)
        with part("Roof"):
            build_roof(layout)
            (build_finished_chimney if DETAILED[0] else build_chimney)(layout)
        with part("Porch and yard"):
            (build_finished_porch if DETAILED[0] else build_porch)(layout)
    if "exterior" in stages:
        build_exterior(layout)
    if "interior" in stages:
        build_interior(layout)
    if "objects" in stages:
        build_objects(layout)
    if "aids" in stages:
        build_aids(layout)
    print(f"CarrieHouse rebuilt: {len(collection(COLLECTION).all_objects)} objects, {len(collection(AIDS).objects)} aids")


if __name__ == "__main__":
    if SOURCE_PATH.exists():
        bpy.ops.wm.open_mainfile(filepath=str(SOURCE_PATH))
    else:
        bpy.ops.wm.read_homefile(use_empty=True)
    build()
    bpy.ops.wm.save_as_mainfile(filepath=str(SOURCE_PATH))
