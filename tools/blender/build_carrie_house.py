def leaf_frame(w: dict, o: dict, hinge: str, swing: float, angle: float, thick: float = 0.045):
    """Maps a door leaf's own coordinates (u across from the hinge edge, y up from just above the
    sill, d through from the face on the swing side) into the house, for a leaf hung on the 'a' or
    'b' jamb of opening o and opened `angle` degrees toward side `swing` (+1 or -1 across the wall)."""
    along = 1.0 if hinge == "a" else -1.0
    s_hinge = o["a"] + JAMB if hinge == "a" else o["b"] - JAMB
    c_hinge = w["fixed"] + swing * thick / 2.0
    t = radians(angle)
    width_dir = (along * cos(t), swing * sin(t))
    thick_dir = (along * sin(t), -swing * cos(t))
    base = o["y0"] + 0.01

    def to_house(u, y, d):
        s = s_hinge + u * width_dir[0] + d * thick_dir[0]
        c = c_hinge + u * width_dir[1] + d * thick_dir[1]
        return (s, base + y, c) if w["axis"] == "x" else (c, base + y, s)

    return to_house


def door_leaf(name: str, w: dict, o: dict, hinge: str, swing: float, angle: float, design: str, mat: str) -> None:
    """A panelled leaf hung in opening o: "front" has three tall lites over panels and a shelf
    outside, "back" four lites over two panels, "five" five flat panels. The outside face is the
    one away from the swing."""
    thick, stile, top_rail, bottom_rail = 0.045, 0.12, 0.12, 0.24
    to_house = leaf_frame(w, o, hinge, swing, angle, thick)
    width = o["b"] - o["a"] - 2.0 * JAMB
    height = o["y1"] - JAMB - (o["y0"] + 0.01)
    inner = (stile, width - stile)
    kit = Kit(name)

    def add(u, y, d=(0.0, thick), part_mat=mat):
        (u0, u1), (y0, y1), (d0, d1) = u, y, d
        corners = [(u0, y0, d0), (u1, y0, d0), (u1, y0, d1), (u0, y0, d1),
                   (u0, y1, d0), (u1, y1, d0), (u1, y1, d1), (u0, y1, d1)]
        kit.add([to_house(*p) for p in corners], BOX_FACES, part_mat)

    add((0.0, stile), (0.0, height))
    add((width - stile, width), (0.0, height))
    add(inner, (0.0, bottom_rail))
    add(inner, (height - top_rail, height))
    if design == "five":
        rail = 0.08
        panel = (height - top_rail - bottom_rail - 4.0 * rail) / 5.0
        for k in range(1, 5):
            y = bottom_rail + k * panel + (k - 1) * rail
            add(inner, (y, y + rail))
        add(inner, (bottom_rail, height - top_rail), (0.012, thick - 0.012))
    else:
        lock = (0.92, 1.08)
        glass = (1.55 if design == "front" else lock[1], height - top_rail)
        add(inner, lock)
        add(inner, (bottom_rail, glass[0]), (0.012, thick - 0.012))          # recessed panels
        mullions = [(bottom_rail, lock[0])]
        if design == "front":
            add(inner, (1.45, glass[0]))                                     # rail under the lites
            add((0.08, width - 0.08), (1.47, 1.53), (thick, thick + 0.03))   # shelf outside
            mullions.append((lock[1], 1.45))
        for y in mullions:
            add((width / 2.0 - 0.05, width / 2.0 + 0.05), y)
        add(inner, glass, (thick / 2.0 - 0.003, thick / 2.0 + 0.003), "WindowGlass")
        bars = (0.008, thick - 0.008)
        if design == "front":                                                # three tall lites
            for k in (1, 2):
                m = stile + k * (width - 2.0 * stile) / 3.0
                add((m - 0.02, m + 0.02), glass, bars)
        else:                                                                # four lites
            add((width / 2.0 - 0.015, width / 2.0 + 0.015), glass, bars)
            middle = sum(glass) / 2.0
            add(inner, (middle - 0.015, middle + 0.015), bars)
    for d in ((-0.06, 0.0), (thick, thick + 0.06)):                         # knobs and plates, both faces
        add((width - 0.085, width - 0.045), (0.98, 1.02), d, "Brass")
    for d in ((-0.006, 0.0), (thick, thick + 0.006)):
        add((width - 0.095, width - 0.035), (0.9, 1.12), d, "Brass")
    kit.build()


