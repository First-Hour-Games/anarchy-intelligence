def load_module(name: str):
    """A module from tools/blender/carrie_house, loaded fresh (and without a __pycache__)."""
    import types
    path = LAYOUT_DIR / f"{name}.py"
    module = types.ModuleType("carrie_house_" + name)
    module.__file__ = str(path)
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    return module


def load_layout():
    return load_module("layout")


def exterior_heights(layout) -> dict:
    """Bands up the outside walls: stone foundation, water table and its drip cap, siding, the
    frieze board, and the soffit under the eaves."""
    eave = layout.ATTIC - ROOF_OVERHANG * ROOF_PITCH
    return {"stone": (layout.GRADE - 0.3, layout.GROUND + 0.1), "deck": layout.GROUND - 0.05,
            "water_table": (layout.GROUND + 0.1, layout.GROUND + 0.28),
            "drip": (layout.GROUND + 0.28, layout.GROUND + 0.3),
            "siding": (layout.GROUND + 0.3, eave - 0.11), "frieze": (eave - 0.11, eave - 0.02),
            "soffit": (eave - 0.02, eave), "eave": eave}


def storeys(layout) -> list:
    """(floor, bottom, top) per storey from the cellar up: each runs from the underside of its
    floor slab to the underside of the next."""
    slabs = {round(y_top, 3): thickness for _, y_top, thickness, _, _ in layout.floors}
    floors = [layout.CELLAR, layout.GROUND, layout.UPPER, layout.ATTIC]
    bottoms = [floor - slabs[round(floor, 3)] for floor in floors] + [99.0]
    return [(floor, bottoms[i], bottoms[i + 1]) for i, floor in enumerate(floors)]


def room_at(layout, x: float, y: float, z: float):
    """(storey index, storey floor, room name, or "" outside the named rooms) at a point inside the
    house, or None outside it."""
    inset = layout.EXT_T
    if not (HOUSE[0] + inset - 1e-6 <= x <= HOUSE[1] - inset + 1e-6 and HOUSE[2] + inset - 1e-6 <= z <= HOUSE[3] - inset + 1e-6):
        return None
    for index, (floor, bottom, top) in enumerate(storeys(layout)):
        if bottom <= y < top:
            break
    else:
        return None
    for name, room_floor, x0, x1, z0, z1 in layout.rooms:
        if abs(room_floor - floor) < 0.01 and x0 - 1e-6 <= x <= x1 + 1e-6 and z0 - 1e-6 <= z <= z1 + 1e-6:
            return index, floor, name
    return index, floor, ""


def finish_at(layout, x: float, y: float, z: float):
    """(storey floor, room finish) at a point inside the house, or None outside it."""
    found = room_at(layout, x, y, z)
    if found is None:
        return None
    index, floor, name = found
    return floor, ROOM_FINISH[name] if name else STOREY_FINISH[index]


