def material(name: str) -> bpy.types.Material:
    if name in _materials:
        return _materials[name]
    if name in TEXTURES:
        result = texture_material(name)
    else:
        greybox = name in GREYBOX
        full = ("Greybox_" if greybox else "House_") + name
        result = bpy.data.materials.get(full) or bpy.data.materials.new(full)
        r, g, b, a = GREYBOX[name] if greybox else FINISHES[name]
        roughness, metallic = SHINE.get(name, (0.8, 0.0))
        result.use_nodes = True
        shader = next(node for node in result.node_tree.nodes if node.type == "BSDF_PRINCIPLED")
        shader.inputs["Base Color"].default_value = (r, g, b, 1.0)
        shader.inputs["Roughness"].default_value = roughness
        shader.inputs["Metallic"].default_value = metallic
        shader.inputs["Alpha"].default_value = a
        result.diffuse_color = (r, g, b, a)
        if a < 1.0:
            result.surface_render_method = "BLENDED"
    _materials[name] = result
    return result


def texture_material(name: str) -> bpy.types.Material:
    """Principled BSDF fed by a colour map and an OpenGL normal map."""
    spec = TEXTURES[name]
    result = bpy.data.materials.get("House_" + name) or bpy.data.materials.new("House_" + name)
    result.use_nodes = True
    nodes, links = result.node_tree.nodes, result.node_tree.links
    nodes.clear()
    output = nodes.new("ShaderNodeOutputMaterial")
    shader = nodes.new("ShaderNodeBsdfPrincipled")
    color = nodes.new("ShaderNodeTexImage")
    normal = nodes.new("ShaderNodeTexImage")
    bump = nodes.new("ShaderNodeNormalMap")
    for node, x, y in ((output, 300, 0), (shader, 0, 0), (color, -450, 150), (normal, -700, -250), (bump, -250, -250)):
        node.location = (x, y)
    color.image = load_image(spec["color"], data=False)
    normal.image = load_image(spec["normal"], data=True)
    links.new(color.outputs["Color"], shader.inputs["Base Color"])
    links.new(normal.outputs["Color"], bump.inputs["Color"])
    links.new(bump.outputs["Normal"], shader.inputs["Normal"])
    links.new(shader.outputs["BSDF"], output.inputs["Surface"])
    shader.inputs["Roughness"].default_value = spec["roughness"]
    nodes.active = color            # the image the viewport's texture colour mode shows
    result.diffuse_color = (*spec["preview"], 1.0)
    return result


def load_image(relative: str, data: bool) -> bpy.types.Image:
    path = TEXTURE_DIR / relative
    image = bpy.data.images.get(path.name) or bpy.data.images.load(str(path))
    if bpy.data.filepath:
        image.filepath = bpy.path.relpath(str(path))
    if data:
        for colorspace in ("Non-Color", "Raw", "Data"):
            try:
                image.colorspace_settings.name = colorspace
                break
            except TypeError:
                continue
    return image


# --- Collections and meshes ---------------------------------------------------------------------

def collection(name: str) -> bpy.types.Collection:
    found = bpy.data.collections.get(name)
    if found is None:
        found = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(found)
    return found


def house_root() -> bpy.types.Object:
    root = bpy.data.objects.get(ROOT_NAME)
    if root is None:
        root = bpy.data.objects.new(ROOT_NAME, None)
        root.empty_display_type = "ARROWS"
        collection(COLLECTION).objects.link(root)
    root.rotation_euler = (radians(90.0), 0.0, 0.0)
    return root


_part = ["Ground floor"]


class part:
    """Objects created inside `with part("Roof"):` go into that child collection."""

    def __init__(self, name: str) -> None:
        self.name = name

    def __enter__(self):
        self.previous = _part[0]
        _part[0] = self.name

    def __exit__(self, *exc):
        _part[0] = self.previous


def part_collection() -> bpy.types.Collection:
    name = "CH " + _part[0]
    found = bpy.data.collections.get(name)
    if found is None:
        found = bpy.data.collections.new(name)
        collection(COLLECTION).children.link(found)
    return found


def clear() -> None:
    for name in (COLLECTION, AIDS):
        found = bpy.data.collections.get(name)
        if found is None:
            continue
        for obj in list(found.all_objects):
            data = obj.data
            bpy.data.objects.remove(obj, do_unlink=True)
            if isinstance(data, bpy.types.Mesh) and data.users == 0:
                bpy.data.meshes.remove(data)
            elif isinstance(data, bpy.types.Curve) and data.users == 0:
                bpy.data.curves.remove(data)


def mesh_object(name: str, verts: list, faces: list, mats, into: str = COLLECTION,
                face_mats: list | None = None) -> bpy.types.Object:
    """One object from closed shapes. mats is a material name, or a list that face_mats indexes.
    Faces get planar UVs at each texture's real size: across and up on walls, up-slope on roofs."""
    import bmesh
    from mathutils import Vector
    mats = [mats] if isinstance(mats, str) else list(mats)
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    for polygon, index in zip(mesh.polygons, face_mats or []):
        polygon.material_index = index
    shell = bmesh.new()
    shell.from_mesh(mesh)
    bmesh.ops.recalc_face_normals(shell, faces=shell.faces)     # outward, whatever the vertex order
    shell.normal_update()
    uv = shell.loops.layers.uv.new("UVMap")
    up, east, south = Vector((0.0, 1.0, 0.0)), Vector((1.0, 0.0, 0.0)), Vector((0.0, 0.0, 1.0))
    for face in shell.faces:
        spec = TEXTURES.get(mats[face.material_index])
        tile_u, tile_v = spec["tile"] if spec else (1.0, 1.0)
        u = up.cross(face.normal)
        level = u.length < 1e-4
        if level:
            u = south if spec and spec["level_z"] else east
        u = u.normalized()
        v = face.normal.cross(u)
        turn = spec is not None and spec["turn"] and not level
        for loop in face.loops:
            s, t = loop.vert.co.dot(u), loop.vert.co.dot(v)
            loop[uv].uv = (t / tile_u, s / tile_v) if turn else (s / tile_u, t / tile_v)
    shell.to_mesh(mesh)
    shell.free()
    for mat in mats:
        mesh.materials.append(material(mat))
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    (part_collection() if into == COLLECTION else collection(into)).objects.link(obj)
    obj.parent = house_root()
    return obj


BOX_FACES = [(0, 1, 2, 3), (4, 7, 6, 5), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]


class Kit:
    """Closed shapes gathered into one object, with a material slot per material used."""

    def __init__(self, name: str) -> None:
        self.name = name
        self.verts, self.faces, self.face_mats, self.mats = [], [], [], []

    def add(self, verts: list, faces: list, mat) -> "Kit":
        """mat: one material name, or one per face."""
        per_face = [mat] * len(faces) if isinstance(mat, str) else mat
        base = len(self.verts)
        self.verts += [tuple(v) for v in verts]
        for face, name in zip(faces, per_face):
            if name not in self.mats:
                self.mats.append(name)
            self.faces.append(tuple(base + i for i in face))
            self.face_mats.append(self.mats.index(name))
        return self

    def box(self, low: tuple, high: tuple, mat, top: str | None = None, bottom: str | None = None) -> "Kit":
        """An axis-aligned box; `top` and `bottom` give its level faces their own materials."""
        (x0, x1), (y0, y1), (z0, z1) = (sorted(pair) for pair in zip(low, high))
        if min(x1 - x0, y1 - y0, z1 - z0) < 1e-4:
            return self
        verts = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1),
                 (x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)]
        if top is None and bottom is None:
            return self.add(verts, BOX_FACES, mat)
        return self.add(verts, BOX_FACES, [bottom or mat, top or mat, mat, mat, mat, mat])

    def along(self, axis: str, s: tuple, y: tuple, c: tuple, mat, top: str | None = None) -> "Kit":
        """A box placed along a wall: s along its axis, y up and c across it, all absolute."""
        if axis == "x":
            return self.box((s[0], y[0], c[0]), (s[1], y[1], c[1]), mat, top)
        return self.box((c[0], y[0], s[0]), (c[1], y[1], s[1]), mat, top)

    def slanted(self, axis: str, c: tuple, a: float, b: float, bottom: float, top_a: float, top_b: float,
                mat) -> "Kit":
        """A wall piece from a to b along its axis, c across it, whose top runs from top_a to top_b.
        mat: one material, or six in BOX_FACES order (bottom, top, c0 side... see build_wall)."""
        c0, c1 = sorted(c)
        if axis == "x":
            verts = [(a, bottom, c0), (b, bottom, c0), (b, bottom, c1), (a, bottom, c1),
                     (a, top_a, c0), (b, top_b, c0), (b, top_b, c1), (a, top_a, c1)]
        else:
            verts = [(c0, bottom, a), (c0, bottom, b), (c1, bottom, b), (c1, bottom, a),
                     (c0, top_a, a), (c0, top_b, b), (c1, top_b, b), (c1, top_a, a)]
        return self.add(verts, BOX_FACES, mat)

    def build(self, into: str = COLLECTION) -> bpy.types.Object | None:
        if not self.faces:
            return None
        if _collector[0] is not None and _collector[0] is not self:
            _collector[0].add(self.verts, self.faces, [self.mats[i] for i in self.face_mats])
            return None
        return mesh_object(self.name, self.verts, self.faces, self.mats, into, self.face_mats)


class Piece:
    """A furniture model's frame: x across the piece, y up from its floor, z from its back (0) to its
    front, turned into the house by `facing`, the way its front looks ("+x", "-x", "+z" or "-z").
    See carrie_house/furniture.py."""

    def __init__(self, kit: Kit, rect: tuple, floor: float, height: float, facing: str) -> None:
        x0, x1, z0, z1 = rect
        across_x = facing in ("+z", "-z")
        self.kit, self.rect, self.floor, self.facing = kit, rect, floor, facing
        self.W = (x1 - x0) if across_x else (z1 - z0)
        self.D = (z1 - z0) if across_x else (x1 - x0)
        self.H = height

    def point(self, x: float, y: float, z: float) -> tuple:
        x0, x1, z0, z1 = self.rect
        y = self.floor + y
        if self.facing == "+z":
            return (x0 + x, y, z0 + z)
        if self.facing == "-z":
            return (x1 - x, y, z1 - z)
        if self.facing == "+x":
            return (x0 + z, y, z1 - x)
        return (x1 - z, y, z0 + x)

    def shape(self, verts: list, faces: list, mat) -> None:
        self.kit.add([self.point(*v) for v in verts], faces, mat)

    def box(self, x0, x1, y0, y1, z0, z1, mat) -> None:
        (x0, x1), (y0, y1), (z0, z1) = sorted((x0, x1)), sorted((y0, y1)), sorted((z0, z1))
        if min(x1 - x0, y1 - y0, z1 - z0) < 1e-5:
            return
        self.shape([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1),
                    (x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)], BOX_FACES, mat)

    def stick(self, a, b, r, mat, r2=None, normal=None) -> None:
        """A rod of square section r from point a to point b; with normal, a board r wide and r2
        thick lying across that normal."""
        from mathutils import Vector
        a, b = Vector(a), Vector(b)
        axis = (b - a).normalized()
        if normal is None:
            helper = Vector((0.0, 1.0, 0.0)) if abs(axis.y) < 0.9 else Vector((1.0, 0.0, 0.0))
            u = axis.cross(helper).normalized()
        else:
            u = axis.cross(Vector(normal)).normalized()
        v = axis.cross(u).normalized()
        r2 = r if r2 is None else r2
        ring = [-u * r - v * r2, u * r - v * r2, u * r + v * r2, -u * r + v * r2]
        self.shape([tuple(a + q) for q in ring] + [tuple(b + q) for q in ring], BOX_FACES, mat)

    def tube(self, a, b, r, mat, sides=10) -> None:
        """A round pipe of `sides` sides from point a to point b."""
        from mathutils import Vector
        a, b = Vector(a), Vector(b)
        axis = (b - a).normalized()
        helper = Vector((0.0, 1.0, 0.0)) if abs(axis.y) < 0.9 else Vector((1.0, 0.0, 0.0))
        u = axis.cross(helper).normalized()
        v = axis.cross(u).normalized()
        ring = [u * (r * cos(2.0 * pi * (k + 0.5) / sides)) + v * (r * sin(2.0 * pi * (k + 0.5) / sides)) for k in range(sides)]
        faces = [tuple(range(sides)), tuple(range(sides, 2 * sides))]
        faces += [(k, (k + 1) % sides, sides + (k + 1) % sides, sides + k) for k in range(sides)]
        self.shape([tuple(a + q) for q in ring] + [tuple(b + q) for q in ring], faces, mat)

    def cyl(self, centre, r, a, b, mat, axis="y", sides=8, r2=None) -> None:
        """A prism of `sides` sides along axis from a to b, centred on centre (its other two
        coordinates in x, y, z order), tapering from radius r to r2."""
        r2 = r if r2 is None else r2
        verts = []
        for t, radius in ((a, r), (b, r2)):
            for k in range(sides):
                angle = 2.0 * pi * (k + 0.5) / sides
                p, q = centre[0] + radius * cos(angle), centre[1] + radius * sin(angle)
                verts.append((p, t, q) if axis == "y" else (t, p, q) if axis == "x" else (p, q, t))
        faces = [tuple(range(sides)), tuple(range(sides, 2 * sides))]
        faces += [(k, (k + 1) % sides, sides + (k + 1) % sides, sides + k) for k in range(sides)]
        self.shape(verts, faces, mat)

    def tray(self, x0, x1, y0, y1, z0, z1, wall, mat, floor=None) -> None:
        """An open-topped box: a floor and four walls."""
        floor = wall if floor is None else floor
        self.box(x0, x1, y0, y0 + floor, z0, z1, mat)
        self.box(x0, x1, y0, y1, z0, z0 + wall, mat)
        self.box(x0, x1, y0, y1, z1 - wall, z1, mat)
        self.box(x0, x0 + wall, y0, y1, z0, z1, mat)
        self.box(x1 - wall, x1, y0, y1, z0, z1, mat)


def box(name: str, low: tuple, high: tuple, mat, into: str = COLLECTION) -> bpy.types.Object:
    return Kit(name).box(low, high, mat).build(into)


def slab_verts(xs: tuple, zs: tuple, ys: tuple, thickness: float) -> list:
    """A flat-sided slab across xs whose top slopes from ys[0] at zs[0] to ys[1] at zs[1]."""
    x0, x1 = xs
    (za, zb), (ya, yb) = zs, ys
    return [(x0, ya - thickness, za), (x1, ya - thickness, za), (x1, yb - thickness, zb), (x0, yb - thickness, zb),
            (x0, ya, za), (x1, ya, za), (x1, yb, zb), (x0, yb, zb)]


def run_prism(axis: str, cross: tuple, a: float, b: float, ya: tuple, yb: tuple) -> list:
    """A piece running along axis from a to b, across cross, from height ya[0] to ya[1] at a and
    from yb[0] to yb[1] at b: rails, stringers and kneewalls on stairs and ladders."""
    c0, c1 = cross
    if axis == "z":
        return [(c0, ya[0], a), (c1, ya[0], a), (c1, yb[0], b), (c0, yb[0], b),
                (c0, ya[1], a), (c1, ya[1], a), (c1, yb[1], b), (c0, yb[1], b)]
    return [(a, ya[0], c0), (b, yb[0], c0), (b, yb[0], c1), (a, ya[0], c1),
            (a, ya[1], c0), (b, yb[1], c0), (b, yb[1], c1), (a, ya[1], c1)]


def sloped_slab(name: str, xs: tuple, zs: tuple, ys: tuple, thickness: float, mat) -> bpy.types.Object:
    """mat: one material, or six in BOX_FACES order (underside, top, then the edges)."""
    return Kit(name).add(slab_verts(xs, zs, ys, thickness), BOX_FACES, mat).build()


def frustum(x: float, z: float, y0: float, y1: float, half0: float, half1: float) -> list:
    """A square column tapering from half-width half0 at y0 to half1 at y1, in box vertex order."""
    return [(x - half0, y0, z - half0), (x + half0, y0, z - half0), (x + half0, y0, z + half0), (x - half0, y0, z + half0),
            (x - half1, y1, z - half1), (x + half1, y1, z - half1), (x + half1, y1, z + half1), (x - half1, y1, z + half1)]


# --- Walls --------------------------------------------------------------------------------

def wall_top(w: dict, s: float) -> float:
    if w["slope"] is None:
        return w["y1"]
    ya, yb = w["slope"]
    return ya + (s - w["start"]) / (w["end"] - w["start"]) * (yb - ya)


def wall_spans(w: dict, y0: float, y1: float | None, cuts=()) -> list:
    """Solid (a, b, bottom, top) pieces of a wall between heights y0 and y1 (None: the wall top),
    leaving out its openings. The wall splits into columns at every opening edge, so windows
    stacked on two floors each keep their own gap, and at any extra cuts."""
    holes = [(max(o["a"], w["start"]), min(o["b"], w["end"]), o["y0"], o["y1"]) for o in w["openings"]]
    edges = sorted({w["start"], w["end"]} | {h[0] for h in holes} | {h[1] for h in holes}
                   | {c for c in cuts if w["start"] < c < w["end"]})
    pieces = []
    for a, b in zip(edges, edges[1:]):
        if b - a < 0.005:
            continue
        cursor = y0
        for low, high in sorted((h[2], h[3]) for h in holes if h[0] <= a + 1e-6 and b <= h[1] + 1e-6):
            if y1 is not None and low >= y1:
                break
            if low > cursor:
                pieces.append((a, b, cursor, low))
            cursor = max(cursor, high)
        if y1 is None or cursor < y1:
            pieces.append((a, b, cursor, y1))
    return pieces


def depth_range(w: dict, d0: float, d1: float) -> tuple:
    """Across an exterior wall: from d0 to d1 metres outward of its outer face."""
    out = 1.0 if w["fixed"] >= 0 else -1.0            # front and right walls face +, back and left -
    face = w["fixed"] + out * w["t"] / 2.0
    return (face + out * d0, face + out * d1)


def build_wall(w: dict, layout) -> None:
    """The wall as one object. With room finishes, it splits where rooms meet and between storeys,
    so each face takes the finish of the room it looks into, with that room's baseboard and wainscot."""
    mat = "Exterior" if w["id"].startswith("Ext") else "Interior"
    shell = Kit(w["id"])
    finish = Kit(w["id"] + "_Finish")
    across = (w["fixed"] - w["t"] / 2.0, w["fixed"] + w["t"] / 2.0)
    interior = INTERIOR[0]
    cuts = []
    if interior:
        cuts = [edge for room in layout.rooms for edge in ((room[2], room[3]) if w["axis"] == "x" else (room[4], room[5]))]
    breaks = [bottom for _, bottom, _ in storeys(layout)[1:]] if interior else []
    for a, b, bottom, top in wall_spans(w, w["y0"], None, cuts):
        top_a = wall_top(w, a) if top is None else top
        top_b = wall_top(w, b) if top is None else top
        if max(top_a, top_b) - bottom <= 0.005:
            continue
        for low, high_a, high_b in split_storeys(bottom, top_a, top_b, breaks):
            sides = [mat, mat]
            if interior:
                sides = [side_finish(layout, w, a, b, low, max(high_a, high_b), side, finish) or mat for side in (-1.0, 1.0)]
            shell.slanted(w["axis"], across, a, b, low, high_a, high_b, [mat, mat, sides[0], mat, sides[1], mat])
    shell.build()
    finish.build()
    trim = Kit(w["id"] + "_Trim")
    for o in w["openings"]:
        a, b = max(o["a"], w["start"]), min(o["b"], w["end"])
        if not DETAILED[0]:
            greybox_opening(trim, w, o, a, b)
        elif o["kind"] == "window":
            build_window(trim, w, o, a, b)
        else:
            build_doorway(trim, w, o, a, b)
    trim.build()


def split_storeys(bottom: float, top_a: float, top_b: float, breaks: list) -> list:
    """(bottom, top_a, top_b) pieces of a level-topped wall piece cut at the storey breaks."""
    if abs(top_a - top_b) > 1e-6:
        return [(bottom, top_a, top_b)]
    heights = [bottom] + [y for y in breaks if bottom + 0.01 < y < top_a - 0.01] + [top_a]
    return [(low, high, high) for low, high in zip(heights, heights[1:])]


def side_finish(layout, w: dict, a: float, b: float, low: float, high: float, side: float, kit: Kit):
    """The wall finish facing one side of a wall piece, adding that room's baseboard and wainscot
    to kit; None where the side faces no room."""
    face = w["fixed"] + side * w["t"] / 2.0
    middle, probe = (a + b) / 2.0, face + side * 0.05
    x, z = (middle, probe) if w["axis"] == "x" else (probe, middle)
    found = finish_at(layout, x, (low + high) / 2.0, z)
    if found is None:
        return None
    floor, (walls, _floor, _ceiling, wainscot) = found
    if not low <= floor + 0.01 < high or floor < layout.GRADE - 0.5 or floor >= layout.ATTIC - 0.01:
        return walls
    s0, s1 = a, b                                   # stop short of door casings
    for o in w["openings"]:
        if o["kind"] != "window" and abs(o["y0"] - floor) < 0.02:
            s0 = a + 0.09 if abs(o["b"] - a) < 1e-4 else s0
            s1 = b - 0.09 if abs(o["a"] - b) < 1e-4 else s1
    if s1 - s0 < 0.02:
        return walls

    def strip(y0, y1, depth, mat, s=(s0, s1)):
        if y1 - y0 > 0.005:
            kit.along(w["axis"], s, (y0, y1), (face, face + side * depth), mat)

    if wainscot:
        kind, height = wainscot
        cap = floor + height
        reach = min(cap, high)
        if kind == "WallTile":
            strip(floor, reach, 0.01, "WallTile")
            if reach >= cap - 1e-6:
                strip(cap - 0.03, cap, 0.02, "Trim")
            return walls
        strip(floor, reach, 0.012, "WoodTrim")                        # board-and-batten
        battens = max(1, round((s1 - s0) / 0.4))
        for k in range(battens + 1):
            s = s0 + 0.03 + (s1 - s0 - 0.06) * k / battens
            strip(floor + 0.2, reach - 0.05, 0.024, "WoodTrim", (s - 0.03, s + 0.03))
        if reach >= cap - 1e-6:
            strip(cap - 0.05, cap, 0.035, "WoodTrim")                 # chair rail
    strip(floor, floor + 0.2, 0.018, "WoodTrim")                      # baseboard
    strip(floor + 0.2, floor + 0.225, 0.026, "WoodTrim")              # and its cap moulding
    return walls


def greybox_opening(kit: Kit, w: dict, o: dict, a: float, b: float) -> None:
    """Glass in windows; a yellow casing around doors so they read in the grey-box; boards
    across blocked doors."""
    axis, fixed, t = w["axis"], w["fixed"], w["t"]
    if o["kind"] == "window":
        kit.along(axis, (a, b), (o["y0"], o["y1"]), (fixed - 0.01, fixed + 0.01), "Glass")
        kit.along(axis, (a - 0.08, b + 0.08), (o["y0"] - 0.05, o["y0"]), depth_range(w, 0.0, 0.07), "Casing")
        return
    for side in (-1.0, 1.0):
        c = (fixed + side * t / 2.0, fixed + side * (t / 2.0 + 0.02))
        kit.along(axis, (a - 0.06, a), (o["y0"], o["y1"] + 0.06), c, "Casing")
        kit.along(axis, (b, b + 0.06), (o["y0"], o["y1"] + 0.06), c, "Casing")
        kit.along(axis, (a - 0.06, b + 0.06), (o["y1"], o["y1"] + 0.06), c, "Casing")
    if o["kind"] == "boarded":
        kit.along(axis, (a, b), (o["y0"], o["y1"]), (fixed - 0.02, fixed + 0.02), "Interior")
        for height in (0.5, 1.1, 1.7):
            y = o["y0"] + height
            kit.along(axis, (a - 0.12, b + 0.12), (y, y + 0.14), (fixed - t / 2.0 - 0.05, fixed - t / 2.0 - 0.02), "Blocked")


def build_window(kit: Kit, w: dict, o: dict, a: float, b: float) -> None:
    """Double-hung 3-over-1 window: painted casing, sill and apron outside, sashes with muntins and
    glass, stained casing and stool inside."""
    axis, t = w["axis"], w["t"]
    y0, y1 = o["y0"], o["y1"]
    key = (w["id"], round(a, 2), round(y0, 2))

    def add(s, y, d, mat):
        kit.along(axis, s, y, depth_range(w, *d), mat)

    # Jambs: painted outside the sashes, stained inside.
    for s in ((a, a + JAMB), (b - JAMB, b), (a, b)):
        y = (y1 - JAMB, y1) if s == (a, b) else (y0, y1)
        add(s, y, (-0.12, 0.0), "Trim")
        add(s, y, (-t, -0.12), "WoodTrim")
    # Outside: casing up to the frieze, drip cap where it fits, sill and apron.
    frieze = HEIGHTS["frieze"][0]
    head = min(y1 + 0.12, frieze)
    add((a - 0.1, a), (y0, head), (0.0, 0.03), "Trim")
    add((b, b + 0.1), (y0, head), (0.0, 0.03), "Trim")
    add((a, b), (y1, head), (0.0, 0.03), "Trim")
    if head + 0.025 <= frieze:
        add((a - 0.12, b + 0.12), (head, head + 0.025), (0.0, 0.05), "Trim")
    add((a - 0.13, b + 0.13), (y0 - 0.05, y0 + 0.01), (-0.08, 0.07), "Trim")
    add((a - 0.08, b + 0.08), (y0 - 0.13, y0 - 0.05), (0.0, 0.028), "Trim")
    # Sashes: the upper one outside the lower one, meeting halfway.
    s0, s1, low, high = a + JAMB, b - JAMB, y0 + 0.01, y1 - JAMB
    middle = (low + high) / 2.0
    upper, lower = (-0.075, -0.04), (-0.12, -0.085)
    for d, bottom, top in ((upper, middle - 0.02, high), (lower, low, middle + 0.02)):
        add((s0, s0 + 0.05), (bottom, top), d, "Sash")
        add((s1 - 0.05, s1), (bottom, top), d, "Sash")
        add((s0, s1), (middle - 0.02, middle + 0.02), d, "Sash")         # meeting rails
    add((s0, s1), (high - 0.06, high), upper, "Sash")
    add((s0, s1), (low, low + 0.08), lower, "Sash")
    for k in (1, 2):                                                     # three lites over one
        m = s0 + 0.05 + k * (s1 - s0 - 0.1) / 3.0
        add((m - 0.011, m + 0.011), (middle + 0.02, high - 0.06), (-0.07, -0.045), "Sash")
    add((s0 + 0.04, s1 - 0.04), (middle, high - 0.04), (-0.0585, -0.0565), "WindowGlass")
    if key not in BROKEN_PANES:
        add((s0 + 0.04, s1 - 0.04), (low + 0.06, middle), (-0.1035, -0.1015), "WindowGlass")
    if key in BOARDED_WINDOWS:
        for y in (y0 + 0.15, middle - 0.07, y1 - 0.3):
            add((a - 0.15, b + 0.15), (y, y + 0.14), (0.03, 0.055), "OldWood")
    # Inside: stool, casing with a cap, apron.
    add((a - 0.12, b + 0.12), (y0, y0 + 0.03), (-t - 0.05, -0.12), "WoodTrim")
    add((a - 0.09, a), (y0 + 0.03, y1 + 0.11), (-t - 0.02, -t), "WoodTrim")
    add((b, b + 0.09), (y0 + 0.03, y1 + 0.11), (-t - 0.02, -t), "WoodTrim")
    add((a, b), (y1, y1 + 0.11), (-t - 0.02, -t), "WoodTrim")
    add((a - 0.11, b + 0.11), (y1 + 0.11, y1 + 0.13), (-t - 0.035, -t), "WoodTrim")
    add((a - 0.09, b + 0.09), (y0 - 0.09, y0), (-t - 0.02, -t), "WoodTrim")


def build_doorway(kit: Kit, w: dict, o: dict, a: float, b: float) -> None:
    """Doors and cased openings: stained jambs and casings, a painted casing and drip cap on the
    outside of exterior doors with an oak threshold, and boards across the sewing-room door."""
    axis, fixed, t = w["axis"], w["fixed"], w["t"]
    y0, y1 = o["y0"], o["y1"]
    exterior = w["id"].startswith("Ext")
    out = 1.0 if fixed >= 0 else -1.0

    def add(s, y, c, mat):
        kit.along(axis, s, y, c, mat)

    through = (fixed - t / 2.0, fixed + t / 2.0)
    add((a, a + JAMB), (y0, y1), through, "WoodTrim")
    add((b - JAMB, b), (y0, y1), through, "WoodTrim")
    add((a, b), (y1 - JAMB, y1), through, "WoodTrim")
    for side in (-1.0, 1.0):
        face = fixed + side * t / 2.0
        if exterior and side == out:
            c = (face, face + side * 0.03)
            add((a - 0.1, a), (y0, y1 + 0.15), c, "Trim")
            add((b, b + 0.1), (y0, y1 + 0.15), c, "Trim")
            add((a, b), (y1, y1 + 0.15), c, "Trim")
            add((a - 0.12, b + 0.12), (y1 + 0.15, y1 + 0.175), (face, face + side * 0.055), "Trim")
        else:
            c = (face, face + side * 0.02)
            add((a - 0.09, a), (y0, y1 + 0.11), c, "WoodTrim")
            add((b, b + 0.09), (y0, y1 + 0.11), c, "WoodTrim")
            add((a, b), (y1, y1 + 0.11), c, "WoodTrim")
            add((a - 0.11, b + 0.11), (y1 + 0.11, y1 + 0.13), (face, face + side * 0.035), "WoodTrim")
    if exterior:
        add((a, b), (y0 - 0.02, y0 + 0.015), (fixed - out * (t / 2.0 - 0.02), fixed + out * (t / 2.0 + 0.05)), "FrontDoor")
    if o["kind"] == "boarded":
        add((a + JAMB, b - JAMB), (y0, y1 - JAMB), (fixed - 0.02, fixed + 0.02), "WoodTrim")
        for height in (0.5, 1.1, 1.7):
            y = y0 + height
            add((a - 0.12, b + 0.12), (y, y + 0.14), (fixed - t / 2.0 - 0.05, fixed - t / 2.0 - 0.02), "OldWood")


