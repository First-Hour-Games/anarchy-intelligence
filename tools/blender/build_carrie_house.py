        kit = Kit("Light_" + "".join(ch for ch in name.title() if ch.isalpha()))
        if name in ("CELLAR", "ATTIC"):
            kit.box((cx - 0.035, ceiling - 0.05, cz - 0.035), (cx + 0.035, ceiling, cz + 0.035), "Iron")
            kit.box((cx - 0.005, ceiling - 0.4, cz - 0.005), (cx + 0.005, ceiling - 0.05, cz + 0.005), "Iron")
